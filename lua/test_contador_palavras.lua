local c = require("contador_palavras")
local f = c.contar("O gato e o rato. O GATO, sim!")
assert(f.o == 3 and f.gato == 2 and f.rato == 1 and f.e == 1 and f.sim == 1)
assert(next(c.contar("")) == nil)
assert(next(c.contar("  ,.;! ")) == nil)
local r = c.ranking("b a b c a b")
assert(r[1][1] == "b" and r[1][2] == 3)
assert(r[2][1] == "a" and r[2][2] == 2)
assert(r[3][1] == "c" and #r == 3)
assert(c.contar("don't stop")["don't"] == 1)
print("ok")
