local e = require("estruturas")
local p = e.nova_pilha()
assert(p:vazia() and p:tamanho() == 0 and p:topo() == nil)
local v, err = p:desempilhar()
assert(v == nil and err == "pilha vazia")
p:empilhar(1); p:empilhar(2); p:empilhar(3)
assert(p:topo() == 3 and p:tamanho() == 3)
assert(p:desempilhar() == 3 and p:desempilhar() == 2 and p:desempilhar() == 1)
assert(p:vazia())

local f = e.nova_fila()
assert(f:vazia())
v, err = f:desenfileirar()
assert(v == nil and err == "fila vazia")
f:enfileirar("a"); f:enfileirar("b"); f:enfileirar("c")
assert(f:tamanho() == 3)
assert(f:desenfileirar() == "a" and f:desenfileirar() == "b")
f:enfileirar("d")
assert(f:desenfileirar() == "c" and f:desenfileirar() == "d")
assert(f:vazia())
f:enfileirar("x")
assert(f:desenfileirar() == "x")
print("ok")
