local r = require("rpn")
assert(r.avaliar("3 4 +") == 7)
assert(r.avaliar("5 1 2 + 4 * + 3 -") == 14)
assert(r.avaliar("2 3 4 * +") == 14)
assert(r.avaliar("10 4 /") == 2.5)
assert(r.avaliar("  42 ") == 42)
assert(r.avaliar("1.5 2 *") == 3.0)
assert(r.avaliar("3 5 -") == -2)
local v, e = r.tentar("1 0 /")
assert(v == nil and e == "divisão por zero")
v, e = r.tentar("1 +")
assert(v == nil and e:find("insuficientes"))
v, e = r.tentar("1 2")
assert(v == nil and e == "expressão malformada")
v, e = r.tentar("")
assert(v == nil)
v, e = r.tentar("1 x +")
assert(v == nil and e:find("inválido"))
print("ok")
