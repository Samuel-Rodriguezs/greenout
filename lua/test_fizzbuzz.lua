local fb = require("fizzbuzz")
local r = fb.fizzbuzz(15)
assert(#r == 15)
assert(r[1] == "1" and r[2] == "2")
assert(r[3] == "Fizz" and r[5] == "Buzz" and r[15] == "FizzBuzz")
assert(r[14] == "14")
assert(#fb.fizzbuzz(0) == 0)
assert(#fb.fizzbuzz(-3) == 0)
assert(fb.converter(30) == "FizzBuzz")
assert(fb.converter(7) == "7")
print("ok")
