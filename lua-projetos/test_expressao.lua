local e = require("expressao")
assert(e.avaliar("1 + 2 * 3") == 7)
assert(e.avaliar("(1 + 2) * 3") == 9)
assert(e.avaliar("10 / 4") == 2.5)
assert(e.avaliar("10 - 3 - 2") == 5)          -- associatividade à esquerda
assert(e.avaliar("2 ^ 3 ^ 2") == 512)         -- associatividade à direita
assert(e.avaliar("-2 ^ 2") == -4)
assert(e.avaliar("--3") == 3)
assert(e.avaliar("-(1 + 2)") == -3)
assert(e.avaliar("7 % 3") == 1)
assert(e.avaliar(".5 + 1.25") == 1.75)
assert(e.avaliar("  42  ") == 42)
assert(e.avaliar("x * 2 + y", { x = 5, y = 1 }) == 11)
assert(e.avaliar("sqrt(16) + abs(-3)") == 7)
assert(e.avaliar("max(1, 5, 3) - min(4, 2)") == 3)
assert(e.avaliar("floor(2.7) + ceil(2.1)") == 5)
assert(e.avaliar("2 * (3 + (4 - 1)) ^ 2") == 72)

local v, m = e.tentar("1 / 0")
assert(v == nil and m == "divisão por zero")
v, m = e.tentar("5 % 0"); assert(v == nil and m == "divisão por zero")
v, m = e.tentar("1 +"); assert(v == nil and m)
v, m = e.tentar(""); assert(v == nil and m)
v, m = e.tentar("(1 + 2"); assert(v == nil and m:find("esperado"))
v, m = e.tentar("1 2"); assert(v == nil and m:find("sobrou"))
v, m = e.tentar("a + 1"); assert(v == nil and m == "variável indefinida: a")
v, m = e.tentar("foo(1)"); assert(v == nil and m == "função desconhecida: foo")
v, m = e.tentar("3 $ 4"); assert(v == nil and m:find("caractere inesperado"))

local arv = e.parse("1 + 2")
assert(arv.tipo == "bin" and arv.op == "+" and arv.a.v == 1 and arv.b.v == 2)
print("ok")
